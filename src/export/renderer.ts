import { createHash } from "node:crypto";
import type { Spec } from "../core/types.js";
import { getProfile } from "../profiles/profiles.js";

export interface RenderedArtifact {
  filename: string;
  content: string;
}

function reqTable(rows: { id: string; title: string; priority: string; provenance: string; status: string }[]): string {
  if (rows.length === 0) return "_None._\n";
  return `| ID | Title | Priority | Provenance | Status |\n|----|-------|----------|------------|--------|\n${rows.map((r) => `| ${r.id} | ${r.title} | ${r.priority} | ${r.provenance} | ${r.status} |`).join("\n")}\n`;
}

function esc(s: string): string {
  // Escape pipe chars that break markdown tables, strip control chars (except newline)
  return s.replace(/[\x00-\x09\x0b-\x1f]/g, "").replace(/\|/g, "\\|");
}

export function renderArtifacts(spec: Spec, requested?: string[]): RenderedArtifact[] {
  const profileId = spec.exportConfig.profile || spec.project.profile || "generic";
  const profile = getProfile(profileId);
  let wanted = requested && requested.length > 0 ? requested : profile.artifacts;
  if (wanted.includes("all")) wanted = [...profile.artifacts];
  // Filter to profile-supported artifacts
  wanted = wanted.filter((a) => profile.artifacts.includes(a));
  const out: RenderedArtifact[] = [];
  const has = (n: string) => wanted.includes(n);

  if (has("PRD.md")) {
    out.push({
      filename: "PRD.md",
      content:
        `# PRD — ${esc(spec.project.name)}\n\n` +
        `> Generated by Universal PRD Compiler. Canonical source: \`.prd/spec.json\`. Markdown is a rendered artifact.\n\n` +
        `## Vision\n\n${esc(spec.project.description || "_No description yet._")}\n\n` +
        `## Goals\n\n${spec.goals.length ? spec.goals.map((g) => `- ${esc(g)}`).join("\n") : "_None._"}\n\n` +
        `## Measurable outcomes\n\n${spec.outcomes.length ? spec.outcomes.map((g) => `- ${esc(g)}`).join("\n") : "_None._"}\n\n` +
        `## Users\n\n${spec.users.length ? spec.users.map((g) => `- ${esc(g)}`).join("\n") : "_None._"}\n\n` +
        `## Scope\n\n### In scope\n\n${spec.scope.inScope.length ? spec.scope.inScope.map((g) => `- ${esc(g)}`).join("\n") : "_None._"}\n\n` +
        `### Out of scope\n\n${spec.scope.outOfScope.length ? spec.scope.outOfScope.map((g) => `- ${esc(g)}`).join("\n") : "_None._"}\n\n` +
        `### Non-goals\n\n${spec.scope.nonGoals.length ? spec.scope.nonGoals.map((g) => `- ${esc(g)}`).join("\n") : "_None._"}\n\n` +
        `## Profile\n\n- Stack profile: \`${profile.id}\` (${profile.name})\n- Schema version: \`${spec.schemaVersion}\`\n`,
    });
  }
  if (has("REQUIREMENTS.md")) {
    out.push({
      filename: "REQUIREMENTS.md",
      content:
        `# Requirements — ${esc(spec.project.name)}\n\n` +
        `## Functional requirements\n\n${reqTable(spec.functionalRequirements.map((r) => ({ id: r.id, title: r.title, priority: r.priority, provenance: r.provenance, status: r.status })))}\n` +
        spec.functionalRequirements.map((r) => `### ${r.id} — ${esc(r.title)}\n\n${esc(r.description)}\n\n- Priority: ${r.priority} | Provenance: \`${r.provenance}\` | Status: ${r.status}\n- Depends on: ${r.dependsOn.join(", ") || "—"}\n`).join("\n") +
        `\n## Non-functional requirements\n\n${reqTable(spec.nonFunctionalRequirements.map((r) => ({ id: r.id, title: r.title, priority: r.priority, provenance: r.provenance, status: r.status })))}\n` +
        spec.nonFunctionalRequirements.map((r) => `### ${r.id} — ${esc(r.title)}\n\n${esc(r.description)}\n\n- Priority: ${r.priority} | Provenance: \`${r.provenance}\` | Status: ${r.status}\n`).join("\n"),
    });
  }
  if (has("ACCEPTANCE_CRITERIA.md")) {
    const all = [...spec.functionalRequirements, ...spec.nonFunctionalRequirements];
    out.push({
      filename: "ACCEPTANCE_CRITERIA.md",
      content:
        `# Acceptance criteria — ${esc(spec.project.name)}\n\n` +
        (all.length === 0
          ? "_No requirements yet._\n"
          : all.map((r) => `## ${r.id} — ${esc(r.title)}\n\n${r.acceptanceCriteria.length ? r.acceptanceCriteria.map((a) => `- [ ] **${a.id}** ${esc(a.statement)}${a.testable ? "" : " (not directly testable)"}`).join("\n") : "- [ ] _No acceptance criteria recorded — requirement is incomplete._"}\n`).join("\n")),
    });
  }
  if (has("ARCHITECTURE.md")) {
    out.push({
      filename: "ARCHITECTURE.md",
      content:
        `# Architecture — ${esc(spec.project.name)}\n\n` +
        `Profile: \`${profile.id}\` (${profile.name})\n\n` +
        `## Recommended sections\n\n${profile.characteristics.map((c) => `- ${c}`).join("\n") || "- _None_"}\n\n` +
        `## Conventions (confirm against the actual project)\n\n${profile.conventions.map((c) => `- ${c}`).join("\n") || "- _None_"}\n\n` +
        `## Constraints\n\n${profile.constraints.map((c) => `- ${c}`).join("\n") || "- _None_"}\n\n` +
        `## Dependencies & integrations\n\n${spec.dependencies.length ? spec.dependencies.map((d) => `- ${esc(d)}`).join("\n") : "_None declared._"}\n\n` +
        `## Decisions\n\n${spec.decisions.length ? spec.decisions.map((d) => `- **${d.id}** ${esc(d.title)} — \`${d.provenance}\` / ${d.status}${d.rationale ? `\n  Rationale: ${esc(d.rationale)}` : ""}`).join("\n") : "_None._"}\n`,
    });
  }
  if (has("DATA_MODEL.md")) {
    out.push({
      filename: "DATA_MODEL.md",
      content:
        `# Data model — ${esc(spec.project.name)}\n\n` +
        (spec.entities.length === 0
          ? "_No entities declared. This artifact is conditional; remove it if the project has no persistent domain model._\n"
          : spec.entities.map((e) => `## ${esc(e.name)}\n\n- Attributes: ${e.attributes.join(", ") || "—"}\n- Relations: ${e.relations.join("; ") || "—"}\n`).join("\n")),
    });
  }
  if (has("API_CONTRACTS.md")) {
    out.push({
      filename: "API_CONTRACTS.md",
      content:
        `# API contracts — ${esc(spec.project.name)}\n\n` +
        (spec.interfaces.length === 0
          ? "_No interfaces declared. This artifact is conditional; remove it if the project exposes no API._\n"
          : spec.interfaces.map((i) => `## ${esc(i.name)} (\`${i.kind}\`)\n\n${esc(i.contract || "_Contract TBD._")}\n`).join("\n")),
    });
  }
  if (has("EDGE_CASES.md")) {
    out.push({
      filename: "EDGE_CASES.md",
      content:
        `# Edge cases & failure scenarios — ${esc(spec.project.name)}\n\n` +
        `## Assumptions (must be confirmed before build)\n\n${spec.assumptions.length ? spec.assumptions.map((a) => `- **${a.id}** [${a.status} / \`${a.provenance}\`] ${esc(a.statement)}`).join("\n") : "_None._"}\n\n` +
        `## Open questions\n\n${spec.openQuestions.length ? spec.openQuestions.map((q) => `- **${q.id}**${q.critical ? " **[CRITICAL]**" : ""} [${q.status}] ${esc(q.question)}${q.resolution ? `\n  Resolution: ${esc(q.resolution)}` : ""}`).join("\n") : "_None._"}\n\n` +
        `## Risks\n\n${spec.risks.length ? spec.risks.map((r) => `- **${r.id}** (${r.severity}) ${esc(r.description)}${r.mitigation ? `\n  Mitigation: ${esc(r.mitigation)}` : ""}`).join("\n") : "_None._"}\n`,
    });
  }
  if (has("TEST_PLAN.md")) {
    out.push({
      filename: "TEST_PLAN.md",
      content:
        `# Test plan — ${esc(spec.project.name)}\n\n` +
        `Test categories for profile \`${profile.id}\`: ${profile.testCategories.join(", ")}\n\n` +
        (spec.testCases.length === 0
          ? "_No test cases yet._\n"
          : spec.testCases.map((t) => `## ${t.id} — ${esc(t.title)} (${t.category})\n\n- Verifies: ${t.verifies.join(", ")}\n- Steps:\n${t.steps.map((s, i) => `  ${i + 1}. ${esc(s)}`).join("\n") || "  - _TBD_"}\n- Expected: ${esc(t.expected || "_TBD_")}\n`).join("\n")),
    });
  }
  if (has("TASKS.md")) {
    const all = [...spec.functionalRequirements, ...spec.nonFunctionalRequirements].filter((r) => r.status !== "rejected");
    out.push({
      filename: "TASKS.md",
      content:
        `# Implementation tasks — ${esc(spec.project.name)}\n\n` +
        `> Each task links back to its requirement ID. Do not implement tasks whose requirements are unresolved.\n\n` +
        (all.length === 0 ? "_No requirements to derive tasks from._\n" : all.map((r) => `- [ ] Implement ${r.id} — ${esc(r.title)} (priority ${r.priority}, provenance \`${r.provenance}\`)`).join("\n") + "\n"),
    });
  }
  return out;
}

export function sha256(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

export function buildDecisionsDoc(spec: Spec): string {
  return JSON.stringify({ decisions: spec.decisions, assumptions: spec.assumptions, openQuestions: spec.openQuestions }, null, 2) + "\n";
}
